"""Конфигурация проекта FUNTIK — пути и параметры озвучки.

Все настройки редактируются здесь.
"""

from pathlib import Path

# ---------------------------------------------------------------------------
# Пути
# ---------------------------------------------------------------------------

BASE_DIR: Path = Path(__file__).resolve().parent
VOICES_DIR: Path = BASE_DIR / "voices"
TEXT_DIR: Path = BASE_DIR / "text"
OUTPUT_DIR: Path = BASE_DIR / "output"

# ---------------------------------------------------------------------------
# Голос
# Язык голоса = язык текста.
# Единственный женский русский в Piper: ru_RU-irina-medium
# Мужские: ru_RU-dmitri-medium, ru_RU-denis-medium, ru_RU-ruslan-medium
# ---------------------------------------------------------------------------

DEFAULT_VOICE: str = "ru_RU-irina-medium"

# ---------------------------------------------------------------------------
# Основные настройки (крутите эти)
# ---------------------------------------------------------------------------

# Скорость речи.
# Диапазон: мин. 0.50 … макс. 1.50
# 1.0 = норма, >1 быстрее, <1 медленнее.
# Рекомендуется: 0.90–1.05
SPEECH_SPEED: float = 0.95

# Интонация / живость.
# Диапазон: мин. 0.0 … макс. 1.0
# 0.0 = ровнее, 1.0 = живее.
# Рекомендуется: 0.40–0.80
INTONATION: float = 0.8

# Громкость.
# Диапазон: мин. 0.10 … макс. 2.00
# 1.0 = норма, >1 громче, <1 тише.
# Рекомендуется: 0.80–1.20
VOLUME: float = 1.0

# Нормализация громкости.
# Диапазон: True или False (обычно True)
NORMALIZE_AUDIO: bool = True

# ---------------------------------------------------------------------------
# Паузы (секунды)
# Паузы ставятся только между предложениями (. ! ?) и абзацами.
# Запятые и тире НЕ режут фразу — иначе голос «заикается».
# ---------------------------------------------------------------------------

# Пауза после предложения (. ! ? …).
# Диапазон: мин. 0.00 … макс. 2.00
# 0 = без доп. паузы.
# Рекомендуется: 0.20–0.50
PAUSE_AFTER_SENTENCE: float = 0.35

# Пауза между абзацами (пустая строка в тексте).
# Диапазон: мин. 0.00 … макс. 3.00
# Рекомендуется: 0.50–1.00
PAUSE_AFTER_PARAGRAPH: float = 0.70

# ---------------------------------------------------------------------------
# Тонкая настройка (обычно не трогайте)
# Если задать число вместо None — перебивает INTONATION.
# ---------------------------------------------------------------------------

# Случайность нейросети.
# Диапазон: None или мин. 0.20 … макс. 1.20
# None = берётся из INTONATION.
# Рекомендуется: 0.55–0.85
NOISE_SCALE: float | None = None

# Вариативность ритма внутри слов.
# Диапазон: None или мин. 0.30 … макс. 1.20
# None = берётся из INTONATION.
# Рекомендуется: 0.65–0.95
NOISE_W_SCALE: float | None = None
