"""Конфигурация проекта FUNTIK — пути и параметры озвучки.

Все настройки редактируются здесь.
"""

from pathlib import Path

# ---------------------------------------------------------------------------
# Пути
# ---------------------------------------------------------------------------

BASE_DIR: Path = Path(__file__).resolve().parent
VOICES_DIR: Path = BASE_DIR / "voices"
TEXT_DIR: Path = BASE_DIR / "text"
OUTPUT_DIR: Path = BASE_DIR / "output"

# ---------------------------------------------------------------------------
# Движок озвучки
# Диапазон: "cartoon" | "piper"
#
# cartoon — полудетский мультяшный голос (Edge TTS, нужен интернет)
# piper   — локальный Piper (офлайн, взрослый тембр irina/dmitri)
# ---------------------------------------------------------------------------

ENGINE: str = "cartoon"

# ===========================================================================
# CARTOON — полудетский мультяшный голос (Edge TTS)
# ===========================================================================

# Голос Microsoft.
# Диапазон: "ru-RU-SvetlanaNeural" (жен.) | "ru-RU-DmitryNeural" (муж.)
CARTOON_VOICE: str = "ru-RU-SvetlanaNeural"

# Высота тона (главный «мультяшный» рычаг).
# Формат: "+NHz" или "-NHz"
# Диапазон: мин. "-50Hz" … макс. "+150Hz"
# Рекомендуется для полудетского: "+70Hz" … "+110Hz"
CARTOON_PITCH: str = "+90Hz"

# Скорость речи.
# Формат: "+N%" или "-N%"
# Диапазон: мин. "-50%" … макс. "+50%"
# Рекомендуется: "+0%" … "+15%"
CARTOON_RATE: str = "+8%"

# Громкость.
# Формат: "+N%" или "-N%"
# Диапазон: мин. "-50%" … макс. "+50%"
CARTOON_VOLUME: str = "+0%"

# ===========================================================================
# PIPER — локальный офлайн-движок (если ENGINE = "piper")
# ===========================================================================

# Голос Piper. Язык = язык текста.
# Женский русский: ru_RU-irina-medium
DEFAULT_VOICE: str = "ru_RU-irina-medium"

# Скорость. Диапазон: мин. 0.50 … макс. 1.50. Рекомендуется: 0.95–1.05
SPEECH_SPEED: float = 1.0

# Интонация. Диапазон: мин. 0.0 … макс. 1.0. Рекомендуется: 0.20–0.45
INTONATION: float = 0.35

# Громкость. Диапазон: мин. 0.10 … макс. 2.00
VOLUME: float = 1.0

NORMALIZE_AUDIO: bool = True

# False = текст целиком (ровнее). True = резка по предложениям.
SPLIT_SENTENCES: bool = False

# Паузы (сек), только если SPLIT_SENTENCES = True.
# Диапазон: мин. 0.00 … макс. 2.00
PAUSE_AFTER_SENTENCE: float = 0.25
# Диапазон: мин. 0.00 … макс. 3.00
PAUSE_AFTER_PARAGRAPH: float = 0.70

# Тонкая настройка Piper. None = из INTONATION.
# Диапазон: None или мин. 0.20 … макс. 1.00
NOISE_SCALE: float | None = None
NOISE_W_SCALE: float | None = None
